import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { unzipSync } from 'fflate';
import { parse } from 'yaml';
const model = `<robot name="tree-test"><link name="base"/><link name="arm"/><link name="tool"/><joint name="shoulder" type="fixed"><parent link="base"/><child link="arm"/></joint><joint name="wrist" type="fixed"><parent link="arm"/><child link="tool"/></joint><custom keep="yes"/></robot>`;

test('model rename, chain selection and subtree deletion update exported files and support undo', async ({ page }, testInfo) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: '新建工程', exact: true }).click();
  await page.getByRole('button', { name: '创建工程', exact: true }).click();
  await page.locator('input[type=file][multiple]').setInputFiles({ name: 'robot.urdf', mimeType: 'application/xml', buffer: Buffer.from(model) });
  await page.getByRole('button', { name: '确认导入', exact: true }).click();
  await page.getByRole('menuitem', { name: '机器人模型' }).click();
  await page.locator('.ant-select').filter({ has: page.locator('#tip-link') }).click();
  await page.locator('.ant-select-item-option[title="tool"]').click();
  await page.getByRole('button', { name: '应用模型变更', exact: true }).click();
  await page.getByText('wrist [fixed]', { exact: true }).click();
  await page.getByRole('button', { name: '重命名节点', exact: true }).click();
  await page.getByLabel('节点新名称',{exact:true}).fill('tool_joint');
  await page.getByRole('button', { name: '查看变更', exact: true }).click();
  await page.getByRole('button', { name: '应用模型变更', exact: true }).click();
  await expect(page.getByText('tool_joint [fixed]', { exact: true })).toBeVisible();
  await page.getByText('tool [控制链端点]', { exact: true }).click();
  await page.getByRole('button', { name: '重命名节点', exact: true }).click();
  await page.getByLabel('节点新名称',{exact:true}).fill('tcp');
  await page.getByRole('button', { name: '查看变更', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('APP tip_link：tool → tcp');
  await page.getByRole('button', { name: '应用模型变更', exact: true }).click();
  await page.getByText('shoulder [fixed]', { exact: true }).click();
  await page.getByRole('button', { name: '删除节点', exact: true }).click();
  await page.getByRole('button', { name: '级联删除子树', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('删除 Link：arm、tcp');
  await page.getByRole('button', { name: '应用模型变更', exact: true }).click();
  await expect(page.getByText('tool_joint [fixed]', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  await expect(page.getByText('tool_joint [fixed]', { exact: true })).toBeVisible();
  const downloaded = page.waitForEvent('download');
  await page.getByRole('button', { name: '下载工程', exact: true }).click();
  const path = testInfo.outputPath('robot.rcproj'); await (await downloaded).saveAs(path);
  const entries = unzipSync(await readFile(path));
  const xml = new TextDecoder().decode(entries['models/robot.urdf']);
  expect(xml).toContain('custom keep="yes"'); expect(xml).toContain('name="tool_joint"'); expect(xml).toContain('link="tcp"');
  expect(parse(new TextDecoder().decode(entries['app/config.yaml'])).robot.tip_link).toBe('tcp');
  await page.screenshot({ path: testInfo.outputPath('robot-tree.png'), fullPage: true });
  expect(errors).toEqual([]);
});

test('3D picking selects the tree and preview sliders change only the rendered pose', async ({ page }, testInfo) => {
  const model = `<robot name="preview"><link name="base"><visual><geometry><box size="0.3 0.3 0.05"/></geometry></visual></link><link name="arm"><visual><origin xyz="0.5 0 0"/><geometry><box size="1 0.12 0.12"/></geometry><material name="blue"><color rgba="0.1 0.3 0.8 1"/></material></visual></link><joint name="rotation" type="revolute"><parent link="base"/><child link="arm"/><origin xyz="0 0 0.1"/><axis xyz="0 0 1"/><limit lower="-1" upper="1" velocity="1" effort="10"/></joint></robot>`;
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/'); await page.getByRole('button', { name: '新建工程', exact: true }).click(); await page.getByRole('button', { name: '创建工程', exact: true }).click();
  await page.locator('input[type=file][multiple]').setInputFiles({ name: 'robot.urdf', mimeType: 'application/xml', buffer: Buffer.from(model) });
  await page.getByRole('button', { name: '确认导入', exact: true }).click();
  await page.getByRole('menuitem', { name: '机器人模型' }).click();
  const canvas = page.getByLabel('机器人三维预览'); await expect(canvas).toBeVisible();
  await page.getByRole('button', { name: '适应模型', exact: true }).click();
  const box = (await canvas.boundingBox())!; await canvas.click({ position: { x: box.width / 2, y: box.height / 2 } });
  await expect(page.locator('.robot-preview')).toHaveAttribute('data-selected', 'link:arm');
  await page.getByText('rotation [revolute]', { exact: true }).click();
  await expect(page.locator('.robot-preview')).toHaveAttribute('data-selected', 'joint:rotation');
  const before = await canvas.screenshot();
  const slider = page.getByRole('slider', { name: '关节预览位置' }); await slider.focus(); await slider.press('End');
  await expect(slider).toHaveAttribute('aria-valuenow', '1');
  await slider.blur(); await expect(page.getByRole('tooltip')).not.toBeVisible();
  await expect.poll(async () => Buffer.compare(before, await canvas.screenshot())).not.toBe(0);
  const downloaded = page.waitForEvent('download'); await page.getByRole('button', { name: '下载工程', exact: true }).click();
  const path = testInfo.outputPath('pose.rcproj'); await (await downloaded).saveAs(path);
  expect(new TextDecoder().decode(unzipSync(await readFile(path))['models/robot.urdf'])).toBe(model);
  await page.getByRole('button', { name: '重置姿态', exact: true }).click(); await expect(slider).toHaveAttribute('aria-valuenow', '0');
  await page.getByText('arm', { exact: true }).first().click();
  await page.getByLabel('尺寸 xyz (m)', { exact: true }).fill('2 0.12 0.12');
  await page.getByLabel('尺寸 xyz (m)', { exact: true }).blur();
  const geometryDownload = page.waitForEvent('download'); await page.getByRole('button', { name: '下载工程', exact: true }).click();
  const geometryPath = testInfo.outputPath('geometry.rcproj'); await (await geometryDownload).saveAs(geometryPath);
  expect(new TextDecoder().decode(unzipSync(await readFile(geometryPath))['models/robot.urdf'])).toContain('size="2 0.12 0.12"');
  await page.screenshot({ path: testInfo.outputPath('preview-and-properties.png'), fullPage: true });

  expect(errors).toEqual([]);
});
