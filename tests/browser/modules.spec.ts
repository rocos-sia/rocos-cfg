test('a registered payload module mounts its editor, updates APP, validates and roundtrips through archives and runtime output', async ({ page, browser }, testInfo) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await page.locator('input[type=file]').first().setInputFiles({ name: 'module.rcproj', mimeType: 'application/zip', buffer: Buffer.from(await saveProject(resourceProject())) });
  await page.getByRole('menuitem', { name: 'APP 配置' }).click();
  await page.getByRole('button', { name: '新建附加配置', exact: true }).click();
  await page.getByLabel('附加配置路径').fill('app/loads/tool.yaml');
  await page.getByRole('button', { name: '创建并关联', exact: true }).click();
  const editor = page.getByRole('dialog', { name: '末端负载' });
  await editor.getByRole('spinbutton', { name: '负载质量' }).fill('2.5');
  await editor.getByRole('spinbutton', { name: '质心 X' }).fill('0.15');
  await editor.getByRole('spinbutton', { name: '质心 X' }).blur();
  await page.screenshot({ path: testInfo.outputPath('payload-editor.png'), fullPage: true });
  await editor.getByRole('button', { name: 'Close' }).click();
  await page.getByRole('button', { name: '校验工程', exact: true }).click();
  await expect(page.getByText('0 项错误', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '检查并导出配置', exact: true }).click();
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: '下载运行包', exact: true }).click();
  const runtime = testInfo.outputPath('runtime.zip'); await (await download).saveAs(runtime);
  const entries = unpackZip(await readFile(runtime));
  expect(readYaml(new TextDecoder().decode(entries.get('app/loads/tool.yaml')))).toEqual({ mass: 2.5, com: [0.15, 0n, 0n] });
  expect(readYaml(new TextDecoder().decode(entries.get('app/config.yaml'))).robot.payload).toBe('loads/tool.yaml');
  expect(entries.has('app/payload.yaml')).toBe(false);
  const saved = page.waitForEvent('download'); await page.getByRole('button', { name: '下载工程', exact: true }).click();
  const path = testInfo.outputPath('payload.rcproj'); await (await saved).saveAs(path);
  const restored = await openProject(await readFile(path)); expect(restored.modules?.filter(m => m.id === 'app.payload')).toHaveLength(1);
  const context = await browser.newContext(); const reopened = await context.newPage();
  await reopened.goto(uiOrigin); await reopened.locator('input[type=file]').first().setInputFiles(path);
  await reopened.getByRole('menuitem', { name: 'APP 配置' }).click();
  await reopened.getByRole('button', { name: 'app/loads/tool.yaml', exact: true }).click();
  await expect(reopened.getByRole('dialog').getByRole('spinbutton', { name: '负载质量' })).toHaveValue('2.5');
  await context.close(); expect(errors).toEqual([]);
});

test('unknown optional module metadata and files remain read-only and survive an ordinary project edit', async ({ page }, testInfo) => {
  const p = resourceProject(), file = makeFile('extensions/vendor.yaml', 'vendor.extra', '# vendor document\nfuture: 42\n'); file.owner = 'vendor.extra';
  p.files.push(file); p.modules = [{ id: 'vendor.extra', version: 9, instanceId: 'vendor-instance', required: false, fileIds: [file.id], metadata: { sequence: [3, 2, 1] } }];
  await page.goto('/'); await page.locator('input[type=file]').first().setInputFiles({ name: 'optional.rcproj', mimeType: 'application/zip', buffer: Buffer.from(await saveProject(p)) });
  await page.getByRole('menuitem', { name: 'APP 配置' }).click();
  await expect(page.getByText('未知 · 只读保留')).toBeVisible();
  await page.getByRole('button', { name: 'extensions/vendor.yaml', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: '模块文件' });
  await expect(dialog.getByLabel('模块只读源码')).toHaveAttribute('contenteditable', 'false');
  await expect(dialog.getByRole('button', { name: '应用修改', exact: true })).toHaveCount(0);
  await dialog.getByRole('button', { name: 'Close' }).click();
  await page.getByRole('menuitem', { name: '工程总览' }).click();
  await page.locator('.overview-grid input').fill('with preserved module'); await page.locator('.overview-grid input').blur();
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: '下载工程', exact: true }).click();
  const path = testInfo.outputPath('optional-saved.rcproj'); await (await download).saveAs(path);
  const reopened = await openProject(await readFile(path)); expect(reopened.name).toBe('with preserved module');
  expect(reopened.modules?.find(m => m.id === 'vendor.extra')).toEqual(p.modules[0]);
  expect(textOf(fileById(reopened, file.id)!)).toBe(textOf(file));
});

test('unsupported required modules and future versions offer exact original copying without replacing the workspace', async ({ page }, testInfo) => {
  const p = resourceProject(), contents = unpackZip(await saveProject(p));
  const m = JSON.parse(new TextDecoder().decode(contents.get('rocos-project.json')));
  m.formatVersion = 2; m.project.name = 'Future project'; contents.set('rocos-project.json', utf8.encode(JSON.stringify(m)));
  const future = packZip(contents);
  await page.goto('/'); await page.getByRole('button', { name: '新建工程', exact: true }).click(); await page.getByRole('button', { name: '创建工程', exact: true }).click();
  await page.locator('input[type=file]').first().setInputFiles({ name: 'future.rcproj', mimeType: 'application/zip', buffer: Buffer.from(future) });
  const dialog = page.getByRole('dialog', { name: '工程只读预览' });
  await expect(dialog).toContainText('Future project'); await expect(dialog).toContainText('当前工作区未被替换');
  const download = page.waitForEvent('download'); await dialog.getByRole('button', { name: '复制原始工程包' }).click();
  const path = testInfo.outputPath('copied.rcproj'); await (await download).saveAs(path);
  expect(new Uint8Array(await readFile(path))).toEqual(future);
  await dialog.getByRole('button', { name: 'Close' }).click();
  await expect(page.locator('.project-name strong')).toHaveText('我的机器人');
  m.formatVersion = 1; m.modules[0].version = 100; contents.set('rocos-project.json', utf8.encode(JSON.stringify(m)));
  await page.locator('input[type=file]').first().setInputFiles({ name: 'required.rcproj', mimeType: 'application/zip', buffer: Buffer.from(packZip(contents)) });
  await expect(dialog).toContainText('必要模块或核心入口不受支持');
  await page.screenshot({ path: testInfo.outputPath('readonly-archive.png'), fullPage: true });
});
