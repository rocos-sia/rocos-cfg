export function parameterHelp(role: string, path: string): string {
  let key = role + '.' + path.replace(/\.\d+(?=\.|$)/g, '.#');
  if (role === 'hardware') key = key.replace('hardware.hardware.#.', 'hardware.');
  if (role === 'igh' && path.startsWith('slaves.') && !descriptions[key]) {
    const leaf = path.split('.').at(-1)!;
    key = path.includes('.init_commands.') ? 'igh.' + ({ name:'sdo.name', Type:'sdo.type', type:'sdo.type', Value:'sdo.value', value:'sdo.value' }[leaf] || leaf)
      : 'igh.' + (leaf === 'index' && !path.includes('.entries.') ? 'pdo.index' : leaf === 'name' ? 'entry.name' : leaf);
  }
  return descriptions[key] || descriptions[key.replace(/\.[^.]+$/, '.*')] || '';
}
